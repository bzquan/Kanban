import i18n from 'i18next'
import { initReactI18next } from 'react-i18next'

import en from '../locales/en.json'
import ja from '../locales/ja.json'
import zh from '../locales/zh.json'

export type AppLanguage = 'en' | 'ja' | 'zh'

// Manual language choice persisted by setLanguage; wins over navigator sniffing.
export const LANG_STORAGE_KEY = 'kanban.lang'

const SUPPORTED: readonly AppLanguage[] = ['en', 'ja', 'zh']

function isAppLanguage(value: unknown): value is AppLanguage {
  return value === 'en' || value === 'ja' || value === 'zh'
}

// Priority: kanban.lang (manual choice) → navigator.languages/language prefix → en.
export function detectLanguage(): AppLanguage {
  try {
    const stored = globalThis.localStorage?.getItem(LANG_STORAGE_KEY) ?? null
    if (isAppLanguage(stored)) return stored
  } catch {
    // storage unavailable (private mode / non-browser) — fall through to sniffing
  }
  const candidates = [
    ...(globalThis.navigator?.languages ?? []),
    globalThis.navigator?.language ?? '',
  ]
  for (const candidate of candidates) {
    const base = candidate.toLowerCase().split('-')[0]
    if (isAppLanguage(base)) return base
  }
  return 'en'
}

// Idempotent: later calls resolve on the same (first) init promise.
let initPromise: Promise<unknown> | null = null

export function initI18n(): Promise<void> {
  if (!initPromise) {
    initPromise = i18n.use(initReactI18next).init({
      // Bundles are static JSON (regenerated by scripts/export-resx.mjs), so no backend
      // is needed; the app title uses the existing resx key `Main_Title`.
      resources: {
        en: { ui: en },
        ja: { ui: ja },
        zh: { ui: zh },
      },
      lng: detectLanguage(),
      fallbackLng: 'en',
      supportedLngs: [...SUPPORTED],
      nonExplicitSupportedLngs: true, // 'ja-JP' etc. resolve to their supported base
      defaultNS: 'ui',
      ns: ['ui'],
      returnEmptyString: false,
      // i18next v27 renamed initImmediate→initAsync: false completes init in the
      // same tick, so renderWithProviders can call initI18n() right before render()
      // and have translations ready without awaiting.
      initAsync: false,
      interpolation: { escapeValue: false }, // React escapes text; no double-escaping
    })
  }
  return initPromise.then(() => undefined)
}

export function setLanguage(lang: AppLanguage): void {
  try {
    globalThis.localStorage?.setItem(LANG_STORAGE_KEY, lang)
  } catch {
    // best-effort persistence; the runtime switch below still applies
  }
  void i18n.changeLanguage(lang)
}
